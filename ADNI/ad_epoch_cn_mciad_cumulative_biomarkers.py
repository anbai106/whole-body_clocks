#!/usr/bin/env python3
"""
Cumulative survival analysis of CN-to-MCI/AD conversion in ADNI.

The analysis starts from the participant-level prediction file generated by the
original AD EPOCH development script. That file contains one baseline-CN row per
participant, the CN-to-MCI/AD survival outcome, split labels, and the frozen
AD EPOCH score. All available development participants (train, validation, and
test) are retained because this analysis evaluates incremental association and
prediction within the full ADNI development cohort rather than external model
validation.

Cumulative model order
----------------------
M0: Age + Sex
M1: M0 + Abeta_CSF
M2: M1 + Tau_CSF + PTau_CSF
M3: M2 + SPARE_BA
M4: M3 + SPARE_AD
M5: M4 + AD EPOCH risk score

Biomarker alignment
-------------------
* Age, Sex, SPARE_BA, and SPARE_AD are taken from the exact selected baseline-CN
  MRI row when possible, using PTID + selected baseline visit, with date-based
  fallback.
* For each CSF marker, the subject's first chronologically available nonmissing
  measurement is used, as requested. Its date relative to the baseline MRI is
  retained in QC output so post-baseline measurements can be identified.
* The primary cumulative comparison uses one common complete-case cohort across
  all six models, ensuring each incremental C-index comparison uses identical
  participants.

Outputs
-------
* baseline analysis dataset
* baseline matching and first-CSF QC tables
* missingness and complete-case summaries
* model performance with apparent and five-fold out-of-fold C-index
* cumulative incremental comparisons with paired bootstrap delta C-index and
  likelihood-ratio tests
* full-model coefficients / hazard ratios
* participant-level out-of-fold risk predictions
* JSON analysis summary

Required packages
-----------------
pandas, numpy, scipy, scikit-learn, lifelines
"""

