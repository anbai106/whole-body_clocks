def prepare_common_fit_pool(data_all: pd.DataFrame, args):
    data = data_all.copy()
    n_prev = int(data["prevalent_or_prior_to_baseline"].sum())
    data = data.loc[data["prevalent_or_prior_to_baseline"] != 1].copy()
    data = data.loc[data["time_from_baseline_to_disease_or_censor_days"] > 0].copy()

    covars = base_covariates(data, args.include_bp)
    time_col = "time_from_baseline_to_disease_or_censor_days"
    event_col = "disease_case"

    required = [time_col, event_col, "participant_id"] + covars + list(CLOCK_COLUMNS.values())
    fit_pool = data[required].copy()
    numeric_cols = [time_col, event_col] + covars + list(CLOCK_COLUMNS.values())
    for c in numeric_cols:
        fit_pool[c] = pd.to_numeric(fit_pool[c], errors="coerce")
    fit_pool = fit_pool.replace([np.inf, -np.inf], np.nan).dropna().copy()
    fit_pool = fit_pool.loc[fit_pool[time_col] > 0].copy()

    for horizon in HORIZON_ORDER:
        raw_col = CLOCK_COLUMNS[horizon]
        z_col = f"epoch_{horizon}_analysis_z"
        fit_pool[z_col], _, _ = standardize_on_common_pool(fit_pool[raw_col])

    return fit_pool, covars, time_col, event_col, n_prev


def analyze_horizon_models(data_all: pd.DataFrame, args):
    fit_pool, covars, time_col, event_col, n_prev = prepare_common_fit_pool(data_all, args)

    n_case = int(fit_pool[event_col].sum())
    n_noncase = int((fit_pool[event_col] == 0).sum())
    if n_case < args.min_case or n_noncase < args.min_noncase:
        rows = []
        for horizon in HORIZON_ORDER:
            row = empty_result(args, horizon, "insufficient_events")
            row.update(
                {
                    "N": int(len(fit_pool)),
                    "N_case": n_case,
                    "N_noncase": n_noncase,
                    "N_prevalent_excluded": n_prev,
                }
            )
            rows.append(row)
        return pd.DataFrame(rows), pd.DataFrame(), fit_pool, pd.DataFrame()

    # One identical covariate-only reference model for all three EPOCH clocks.
    cph_base, df_base, covars_used, pen_base = fit_cox(
        fit_pool,
        time_col=time_col,
        event_col=event_col,
        predictors=covars,
        penalizer=args.penalizer,
    )
    base_c = model_cindex(cph_base, df_base, time_col, event_col)

    rows = []
    risk_predictions_full = {}
    risk_predictions_clock_only = {}

    followup_years = fit_pool[time_col].astype(float) / 365.25
    event_followup_years = followup_years.loc[fit_pool[event_col] == 1]

    for horizon in HORIZON_ORDER:
        raw_col = CLOCK_COLUMNS[horizon]
        z_col = f"epoch_{horizon}_analysis_z"

        try:
            cph_full, df_full, predictors_used, pen_full = fit_cox(
                fit_pool,
                time_col=time_col,
                event_col=event_col,
                predictors=covars_used + [z_col],
                penalizer=args.penalizer,
            )
            stats = extract_hr(cph_full, z_col)
            full_c = model_cindex(cph_full, df_full, time_col, event_col)
            # A standard likelihood-ratio test is appropriate only for the
            # unpenalized nested Cox models. If numerical fallback required a
            # penalizer, leave the LRT missing rather than report a nonstandard test.
            if float(pen_base) == 0.0 and float(pen_full) == 0.0:
                lrt_chisq, lrt_p = lrt_stats(cph_full, cph_base, df_diff=1)
            else:
                lrt_chisq, lrt_p = np.nan, np.nan

            # Clock-only ranking, no refitting needed because monotonic rescaling does not alter C-index.
            clock_only_c = cindex_from_risk(
                fit_pool,
                time_col,
                event_col,
                fit_pool[z_col].to_numpy(),
            )
            risk_predictions_full[horizon] = cph_full.predict_log_partial_hazard(
                fit_pool[covars_used + [z_col]]
            ).to_numpy().reshape(-1)
            # The standardized EPOCH itself is a monotonic disease-risk score for
            # the clock-only comparison.
            risk_predictions_clock_only[horizon] = fit_pool[z_col].to_numpy(dtype=float)

            row = empty_result(args, horizon, "ok")
            row.update(
                {
                    "N": int(len(fit_pool)),
                    "N_case": n_case,
                    "N_noncase": n_noncase,
                    "N_prevalent_excluded": n_prev,
                    "event_rate": float(n_case / len(fit_pool)),
                    "followup_years_min": float(followup_years.min()),
                    "followup_years_median": float(followup_years.median()),
                    "followup_years_max": float(followup_years.max()),
                    "event_followup_years_min": float(event_followup_years.min()),
                    "event_followup_years_median": float(event_followup_years.median()),
                    "event_followup_years_max": float(event_followup_years.max()),
                    "clock_raw_mean": float(fit_pool[raw_col].mean()),
                    "clock_raw_sd": float(fit_pool[raw_col].std(ddof=1)),
                    "clock_beta": stats["beta"],
                    "clock_se": stats["se"],
                    "clock_hr_per_1sd": stats["hr"],
                    "clock_ci_lo": stats["ci_lo"],
                    "clock_ci_hi": stats["ci_hi"],
                    "clock_p": stats["p"],
                    "clock_only_cindex": clock_only_c,
                    "covariate_only_cindex": base_c,
                    "full_model_cindex": full_c,
                    "delta_cindex_full_minus_covariates": full_c - base_c,
                    "lrt_chisq_clock_vs_covariates": lrt_chisq,
                    "lrt_p_clock_vs_covariates": lrt_p,
                    "penalizer_covariate_model": pen_base,
                    "penalizer_full_model": pen_full,
                    "covariates_used": ",".join(covars_used),
                }
            )
        except Exception as exc:
            row = empty_result(args, horizon, "cox_fit_failed", str(exc))
            row.update(
                {
                    "N": int(len(fit_pool)),
                    "N_case": n_case,
                    "N_noncase": n_noncase,
                    "N_prevalent_excluded": n_prev,
                }
            )
        rows.append(row)

    res = pd.DataFrame(rows)

    pairwise = paired_bootstrap_cindex_comparisons(
        fit_pool,
        time_col,
        event_col,
        {
            "covariates_plus_epoch": risk_predictions_full,
            "epoch_only": risk_predictions_clock_only,
        },
        args.n_bootstrap,
        args.random_state,
        args,
    )
    corr = clock_correlations(fit_pool)
    return res, pairwise, fit_pool, corr


def paired_bootstrap_cindex_comparisons(
    fit_pool: pd.DataFrame,
    time_col: str,
    event_col: str,
    risk_prediction_sets: Dict[str, Dict[str, np.ndarray]],
    n_boot: int,
    random_state: int,
    args,
) -> pd.DataFrame:
    rows = []
    n = len(fit_pool)
    time = fit_pool[time_col].to_numpy(dtype=float)
    event = fit_pool[event_col].to_numpy(dtype=int)

    for prediction_type, risk_predictions in risk_prediction_sets.items():
        for pair_index, (a, b) in enumerate(combinations(HORIZON_ORDER, 2)):
            if a not in risk_predictions or b not in risk_predictions:
                continue
            ra = np.asarray(risk_predictions[a], dtype=float)
            rb = np.asarray(risk_predictions[b], dtype=float)
            c_a = float(concordance_index(time, -ra, event))
            c_b = float(concordance_index(time, -rb, event))
            delta = c_a - c_b

            type_offset = 0 if prediction_type == "covariates_plus_epoch" else 100000
            rng = np.random.default_rng(
                random_state + type_offset + 1000 * (pair_index + 1)
            )
            boots = []
            for _ in range(n_boot):
                idx = rng.integers(0, n, size=n)
                if np.sum(event[idx]) < 2 or np.sum(event[idx] == 0) < 2:
                    continue
                try:
                    ca = float(concordance_index(time[idx], -ra[idx], event[idx]))
                    cb = float(concordance_index(time[idx], -rb[idx], event[idx]))
                    d = ca - cb
                    if np.isfinite(d):
                        boots.append(d)
                except Exception:
                    continue

            boots = np.asarray(boots, dtype=float)
            if boots.size:
                lo, hi = np.quantile(boots, [0.025, 0.975])
                p_le0 = float(np.mean(boots <= 0.0))
                p_ge0 = float(np.mean(boots >= 0.0))
                p2 = float(min(1.0, 2.0 * min(p_le0, p_ge0)))
            else:
                lo = hi = p2 = p_le0 = np.nan

            rows.append(
                {
                    "endpoint": args.endpoint,
                    "endpoint_label": ENDPOINTS[args.endpoint]["label"],
                    "analysis_split": args.analysis_split,
                    "prediction_type": prediction_type,
                    "comparison": f"{a}_minus_{b}",
                    "model_a": a,
                    "model_b": b,
                    "cindex_a": c_a,
                    "cindex_b": c_b,
                    "delta_cindex_a_minus_b": delta,
                    "delta_cindex_ci_lower": float(lo) if np.isfinite(lo) else np.nan,
                    "delta_cindex_ci_upper": float(hi) if np.isfinite(hi) else np.nan,
                    "n_bootstrap_requested": int(n_boot),
                    "n_bootstrap_successful": int(boots.size),
                    "empirical_p_two_sided_delta_not_equal_0": p2,
                    "empirical_p_one_sided_delta_le_0": p_le0,
                    "bootstrap_note": (
                        "Participant bootstrap of C-index difference using fixed risk scores; "
                        "disease Cox models are not refit within each bootstrap."
                    ),
                }
            )
    return pd.DataFrame(rows)


def clock_correlations(fit_pool: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for a, b in combinations(HORIZON_ORDER, 2):
        ca = CLOCK_COLUMNS[a]
        cb = CLOCK_COLUMNS[b]
        x = pd.to_numeric(fit_pool[ca], errors="coerce")
        y = pd.to_numeric(fit_pool[cb], errors="coerce")
        ok = x.notna() & y.notna()
        rows.append(
            {
                "horizon_a": a,
                "horizon_b": b,
                "n_pair": int(ok.sum()),
                "pearson_r": float(x[ok].corr(y[ok], method="pearson")),
                "spearman_rho": float(x[ok].corr(y[ok], method="spearman")),
            }
        )
    return pd.DataFrame(rows)


def fmt_p(p: float) -> str:
    if p is None or not np.isfinite(p):
        return "NA"
    if p < 1e-300:
        return "<1e-300"
    if p < 0.001:
        return f"{p:.2e}"
    return f"{p:.3f}"


def make_forest_plot(res: pd.DataFrame, args):
    ok = res.loc[(res["status"] == "ok") & res["clock_hr_per_1sd"].notna()].copy()
    if ok.empty:
        return
    try:
        import matplotlib.pyplot as plt
    except Exception as exc:
        warnings.warn(f"matplotlib is not available; skipping plot: {exc}")
        return

    order_map = {h: i for i, h in enumerate(HORIZON_ORDER)}
    ok["order"] = ok["clock_training_horizon"].map(order_map)
    ok = ok.sort_values("order", ascending=False)

    y = np.arange(ok.shape[0])
    hr = ok["clock_hr_per_1sd"].astype(float).to_numpy()
    lo = ok["clock_ci_lo"].astype(float).to_numpy()
    hi = ok["clock_ci_hi"].astype(float).to_numpy()
    labels = ok["clock_training_horizon"].map(
        {"5y": "5-year EPOCH", "10y": "10-year EPOCH", "full": "Full-follow-up EPOCH"}
    ).to_numpy()

    fig, ax = plt.subplots(figsize=(9.2, 4.6))
    ax.axvline(1.0, linestyle="--", linewidth=1.0)
    ax.errorbar(hr, y, xerr=[hr - lo, hi - hr], fmt="o", capsize=3, linewidth=1.2)
    ax.set_yticks(y)
    ax.set_yticklabels(labels)
    ax.set_xscale("log")
    ax.set_xlabel("Hazard ratio per 1 SD higher baseline Endocrine EPOCH")
    ax.set_title(
        f"{ENDPOINTS[args.endpoint]['label']}: Endocrine mortality EPOCH by training horizon"
    )

    xmax = max(np.nanmax(hi), 1.05)
    xmin = min(np.nanmin(lo), 0.95)
    ax.set_xlim(max(0.2, xmin * 0.85), xmax * 1.8)
    text_x = xmax * 1.08
    for i, row in enumerate(ok.itertuples(index=False)):
        txt = (
            f"HR {row.clock_hr_per_1sd:.2f} ({row.clock_ci_lo:.2f}-{row.clock_ci_hi:.2f}); "
            f"P={fmt_p(row.clock_p)}; C={row.full_model_cindex:.3f}"
        )
        ax.text(text_x, i, txt, va="center", fontsize=8.5)

    ax.grid(axis="x", alpha=0.25)
    fig.tight_layout()
    prefix = os.path.splitext(args.output_tsv)[0]
    for ext in ["png", "pdf", "svg"]:
        fig.savefig(f"{prefix}_horizon_clock_forest_plot.{ext}", dpi=300, bbox_inches="tight")
    plt.close(fig)


