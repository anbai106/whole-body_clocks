#!/usr/bin/env python3
"""
Compare baseline Endocrine metabolomics mortality EPOCH clocks trained with
5-year, 10-year, and full available mortality follow-up for prediction of
incident major diseases.

Primary design
--------------
1. Read the three baseline Endocrine EPOCH acceleration scores generated by
   endocrine_metabolomics_horizon_clocks.py:

     endocrine_metabolomics_mortality_clock_acceleration_z_5y
     endocrine_metabolomics_mortality_clock_acceleration_z_10y
     endocrine_metabolomics_mortality_clock_acceleration_z_full

2. Use baseline assessment/sample date as time zero.
3. Exclude disease events on or before baseline for the endpoint being tested.
4. Censor at the earlier of death or the administrative censor date.
5. Fit the SAME common disease cohort for all three horizon-specific clocks.
6. For each clock, fit:

     Cox(time to disease/censor) ~ common covariates + EPOCH_horizon

   and compare it with the same covariate-only model.
7. Report HR per 1 SD higher EPOCH, 95% CI, Wald P value, likelihood-ratio
   test versus the covariate-only model, Harrell C-index, and incremental C.
8. Compare the three horizon-specific full-model C-indices by paired
   participant bootstrap using fixed fitted-model risk predictions.

By default, the primary analysis uses only participants assigned to the held-out
"test" split during mortality-EPOCH development. This avoids reusing the
mortality-clock training/validation participants for downstream disease
prediction. Set --analysis_split all for a larger sensitivity analysis.
"""

