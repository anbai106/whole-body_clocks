def normalize_participant_id(df: pd.DataFrame, col: str = "participant_id") -> pd.DataFrame:
    if col not in df.columns:
        raise ValueError(f"Missing ID column: {col}")
    out = df.copy()
    out[col] = pd.to_numeric(out[col], errors="coerce").astype("Int64")
    out = out.loc[out[col].notna()].copy()
    out[col] = out[col].astype(int)
    return out


def parse_ukb_date(series: pd.Series) -> pd.Series:
    x = series.copy()
    x = x.replace(
        [0, 0.0, "0", "0.0", "", "NA", "NaN", "nan", "None", "-1", -1],
        np.nan,
    )
    parsed = pd.to_datetime(x, errors="coerce")

    numeric = pd.to_numeric(x, errors="coerce")
    excel_mask = numeric.between(20000, 60000)
    if excel_mask.any():
        excel_dates = pd.to_datetime(
            numeric, unit="D", origin="1899-12-30", errors="coerce"
        )
        parsed = parsed.where(~excel_mask, excel_dates)
    return parsed


def find_ukb_field_column(df: pd.DataFrame, field_id: str, required: bool = True) -> str:
    field_id = str(field_id)
    col_str = {c: str(c) for c in df.columns}

    exact_candidates = [
        field_id,
        f"{field_id}-0.0",
        f"{field_id}_0_0",
        f"f{field_id}",
        f"f{field_id}_0_0",
    ]
    for wanted in exact_candidates:
        for c, s in col_str.items():
            if s == wanted:
                return c

    patterns = [
        rf"(^|[^0-9]){re.escape(field_id)}([^0-9]|$)",
        rf"f{re.escape(field_id)}(_|$)",
    ]
    matches = []
    for c, s in col_str.items():
        for pat in patterns:
            if re.search(pat, s):
                matches.append(c)
                break

    if matches:
        for c in matches:
            s = str(c)
            if s.endswith("-0.0") or s.endswith("_0_0"):
                return c
        return matches[0]

    if required:
        preview = ", ".join(list(map(str, df.columns[:40])))
        raise ValueError(f"Could not find UKB field {field_id}. First columns: {preview}")
    return ""


def read_algorithmic_outcome_dates(args) -> pd.DataFrame:
    info = ENDPOINTS[args.endpoint]
    if not os.path.exists(args.umel_death_xlsx):
        raise FileNotFoundError(args.umel_death_xlsx)
    if not os.path.exists(args.umel_match_csv):
        raise FileNotFoundError(args.umel_match_csv)

    raw = pd.read_excel(args.umel_death_xlsx, engine="openpyxl")
    match = pd.read_csv(args.umel_match_csv)

    if "eid" not in raw.columns:
        raise ValueError("UMelbourne Excel file must contain eid.")
    if not all(c in match.columns for c in ["id", "id_upenn"]):
        raise ValueError("ID match CSV must contain id and id_upenn.")

    disease_col = find_ukb_field_column(raw, info["date_field"], required=True)
    source_col = find_ukb_field_column(raw, info["source_field"], required=False)
    death_col = find_ukb_field_column(raw, DEATH_FIELD, required=False)

    raw = raw.rename(columns={"eid": "participant_id_umel"})
    match = match.rename(columns={"id": "participant_id_umel", "id_upenn": "participant_id"})
    raw = normalize_participant_id(raw, "participant_id_umel")
    match = normalize_participant_id(match, "participant_id_umel")
    match = normalize_participant_id(match, "participant_id")

    keep = ["participant_id_umel", disease_col]
    if source_col:
        keep.append(source_col)
    if death_col:
        keep.append(death_col)

    d = match[["participant_id_umel", "participant_id"]].merge(
        raw[keep], on="participant_id_umel", how="inner"
    )

    out = pd.DataFrame({"participant_id": d["participant_id"].values})
    out["event_date_raw"] = d[disease_col].values
    out["event_date"] = parse_ukb_date(d[disease_col])
    out["event_source"] = d[source_col].values if source_col else np.nan
    out["death_date_algorithmic_file"] = (
        parse_ukb_date(d[death_col]) if death_col else pd.NaT
    )
    out["endpoint"] = args.endpoint
    out["endpoint_label"] = info["label"]
    out["endpoint_date_field"] = info["date_field"]
    out["endpoint_source_field"] = info["source_field"]

    return (
        out.sort_values("participant_id")
        .groupby("participant_id", as_index=False)
        .first()
    )


def coerce_sex_numeric(series: pd.Series) -> pd.Series:
    numeric = pd.to_numeric(series, errors="coerce")
    if numeric.notna().sum() > 0:
        return numeric
    s = series.astype(str).str.strip().str.lower()
    return s.map({"female": 0.0, "f": 0.0, "male": 1.0, "m": 1.0})


def read_covariates(path: str, include_bp: bool) -> pd.DataFrame:
    if not os.path.exists(path):
        raise FileNotFoundError(path)
    cov_all = pd.read_csv(path)
    if "eid" not in cov_all.columns and "participant_id" not in cov_all.columns:
        raise ValueError("Covariate file must contain eid or participant_id.")
    if "eid" in cov_all.columns:
        cov_all = cov_all.rename(columns={"eid": "participant_id"})

    sex_candidates = ["sex_f31_0_0", "genetic_sex_f22001_0_0", "Sex", "sex"]
    sex_col = next((c for c in sex_candidates if c in cov_all.columns), None)

    keep = ["participant_id"]
    rename = {}
    for src, dst in [
        (AGE_RECRUIT_COL, "Age_recruitment_fallback"),
        (SMOKING_COL, "Smoking"),
        (BMI_COL, "BMI"),
        (sex_col, "Sex"),
    ]:
        if src is not None and src in cov_all.columns:
            keep.append(src)
            rename[src] = dst

    if include_bp:
        for src, dst in [
            (DIASTOLIC_COL, "Diastolic"),
            (SYSTOLIC_COL, "Systolic"),
        ]:
            if src in cov_all.columns:
                keep.append(src)
                rename[src] = dst

    cov = cov_all[keep].copy().rename(columns=rename)
    cov = normalize_participant_id(cov, "participant_id")

    if "Sex" in cov.columns:
        cov["Sex"] = coerce_sex_numeric(cov["Sex"])
    for c in cov.columns:
        if c in {"participant_id", "Sex"}:
            continue
        cov[c] = pd.to_numeric(cov[c], errors="coerce")

    return cov.drop_duplicates("participant_id", keep="first")


def read_horizon_clocks(path: str, analysis_split: str) -> pd.DataFrame:
    if not os.path.exists(path):
        raise FileNotFoundError(path)
    df = pd.read_csv(path, sep="\t")
    df = normalize_participant_id(df, "participant_id")

    required = ["participant_id", "sample_date", "split"] + list(CLOCK_COLUMNS.values())
    missing = [c for c in required if c not in df.columns]
    if missing:
        raise ValueError(f"Horizon prediction file is missing columns: {missing}")

    keep = [
        "participant_id",
        "baseline_date" if "baseline_date" in df.columns else None,
        "sample_date",
        "death_date" if "death_date" in df.columns else None,
        "admin_censor_date" if "admin_censor_date" in df.columns else None,
        "age_at_baseline" if "age_at_baseline" in df.columns else None,
        "split",
    ] + list(CLOCK_COLUMNS.values())
    keep = [c for c in keep if c is not None]
    df = df[keep].copy()

    if analysis_split == "test":
        before = df.shape[0]
        df = df.loc[df["split"].astype(str).str.lower() == "test"].copy()
        print(f"Filtered horizon clock predictions to held-out test split: {before} -> {df.shape[0]}")
    else:
        print(f"Using all available horizon clock predictions: N={df.shape[0]}")

    df["sample_date"] = parse_ukb_date(df["sample_date"])
    if "baseline_date" in df.columns:
        df["baseline_date"] = parse_ukb_date(df["baseline_date"])
        df["sample_date"] = df["sample_date"].where(df["sample_date"].notna(), df["baseline_date"])
    if "death_date" in df.columns:
        df["death_date"] = parse_ukb_date(df["death_date"])
    if "admin_censor_date" in df.columns:
        df["admin_censor_date"] = parse_ukb_date(df["admin_censor_date"])
    if "age_at_baseline" in df.columns:
        df["age_at_baseline"] = pd.to_numeric(df["age_at_baseline"], errors="coerce")

    for c in CLOCK_COLUMNS.values():
        df[c] = pd.to_numeric(df[c], errors="coerce")

    return df.drop_duplicates("participant_id", keep="first")


def prepare_survival_dataset(args) -> pd.DataFrame:
    clocks = read_horizon_clocks(args.horizon_predictions, args.analysis_split)
    outcome = read_algorithmic_outcome_dates(args)
    cov = read_covariates(args.cov_tsv, args.include_bp)

    data = clocks.merge(outcome, on="participant_id", how="left")
    data = data.merge(cov, on="participant_id", how="left")

    data["sample_date"] = parse_ukb_date(data["sample_date"])
    data["event_date"] = parse_ukb_date(data["event_date"])
    data["death_date_algorithmic_file"] = parse_ukb_date(data["death_date_algorithmic_file"])
    if "death_date" in data.columns:
        data["death_date"] = parse_ukb_date(data["death_date"])
    else:
        data["death_date"] = pd.NaT

    admin_const = pd.Timestamp(args.admin_censor_date)
    if "admin_censor_date" in data.columns:
        data["admin_censor_date"] = parse_ukb_date(data["admin_censor_date"])
        data["admin_censor_date"] = data["admin_censor_date"].where(
            data["admin_censor_date"].notna(), admin_const
        )
    else:
        data["admin_censor_date"] = admin_const

    data["death_censor_date"] = data["death_date_algorithmic_file"].where(
        data["death_date_algorithmic_file"].notna(), data["death_date"]
    )

    # Use the earlier of death and administrative censoring.
    data["censor_date"] = data["admin_censor_date"]
    death_before_admin = (
        data["death_censor_date"].notna()
        & (data["death_censor_date"] < data["admin_censor_date"])
    )
    data.loc[death_before_admin, "censor_date"] = data.loc[
        death_before_admin, "death_censor_date"
    ]

    # Disease present at or before baseline is excluded from incident-disease analyses.
    data["prevalent_or_prior_to_baseline"] = (
        data["event_date"].notna()
        & data["sample_date"].notna()
        & (data["event_date"] <= data["sample_date"])
    ).astype(int)

    data["incident_event_after_baseline"] = (
        data["event_date"].notna()
        & data["sample_date"].notna()
        & (data["event_date"] > data["sample_date"])
        & (data["event_date"] <= data["censor_date"])
    ).astype(int)

    data["end_date_disease"] = data["censor_date"]
    event_mask = data["incident_event_after_baseline"] == 1
    data.loc[event_mask, "end_date_disease"] = data.loc[event_mask, "event_date"]

    data["time_from_baseline_to_disease_or_censor_days"] = (
        data["end_date_disease"] - data["sample_date"]
    ).dt.days
    data["time_from_baseline_to_disease_or_censor_years"] = (
        data["time_from_baseline_to_disease_or_censor_days"] / 365.25
    )
    data["disease_case"] = data["incident_event_after_baseline"].astype(int)
    data["endpoint"] = args.endpoint
    data["endpoint_label"] = ENDPOINTS[args.endpoint]["label"]
    data["analysis_split"] = args.analysis_split

    # Prefer the exact baseline age carried with the EPOCH prediction file.
    if "age_at_baseline" in data.columns:
        data["Age_baseline"] = pd.to_numeric(data["age_at_baseline"], errors="coerce")
    else:
        data["Age_baseline"] = np.nan
    if "Age_recruitment_fallback" in data.columns:
        data["Age_baseline"] = data["Age_baseline"].where(
            data["Age_baseline"].notna(),
            pd.to_numeric(data["Age_recruitment_fallback"], errors="coerce"),
        )

    return data


def base_covariates(df: pd.DataFrame, include_bp: bool) -> List[str]:
    candidates = ["Age_baseline", "Sex", "Smoking", "BMI"]
    if include_bp:
        candidates.extend(["Diastolic", "Systolic"])

    covars = []
    for c in candidates:
        if c not in df.columns:
            continue
        vals = pd.to_numeric(df[c], errors="coerce")
        if vals.notna().sum() > 0 and vals.nunique(dropna=True) > 1:
            df[c] = vals
            covars.append(c)
    return covars


def standardize_on_common_pool(values: pd.Series) -> Tuple[pd.Series, float, float]:
    x = pd.to_numeric(values, errors="coerce")
    mean = float(x.mean())
    sd = float(x.std(ddof=1))
    if not np.isfinite(sd) or sd <= 0:
        return pd.Series(np.nan, index=x.index), mean, sd
    return (x - mean) / sd, mean, sd


def fit_cox(
    df: pd.DataFrame,
    time_col: str,
    event_col: str,
    predictors: List[str],
    penalizer: float,
):
    cols = [time_col, event_col] + predictors
    fit_df = df[cols].copy()
    for c in cols:
        fit_df[c] = pd.to_numeric(fit_df[c], errors="coerce")
    fit_df = fit_df.replace([np.inf, -np.inf], np.nan).dropna().copy()
    fit_df = fit_df.loc[fit_df[time_col] > 0].copy()

    usable = []
    for c in predictors:
        if fit_df[c].nunique(dropna=True) > 1:
            usable.append(c)
    fit_df = fit_df[[time_col, event_col] + usable].copy()

    if int(fit_df[event_col].sum()) == 0 or int((fit_df[event_col] == 0).sum()) == 0:
        raise ValueError("No cases or no non-cases in complete-case fit_df.")

    penalties = []
    for pen in [penalizer, 0.001, 0.01, 0.1]:
        if pen not in penalties:
            penalties.append(pen)

    last_error = None
    for pen in penalties:
        try:
            cph = CoxPHFitter(penalizer=pen)
            cph.fit(
                fit_df,
                duration_col=time_col,
                event_col=event_col,
                show_progress=False,
            )
            return cph, fit_df, usable, pen
        except Exception as exc:
            last_error = exc
    raise last_error


def extract_hr(cph: CoxPHFitter, var: str) -> Dict[str, float]:
    beta = float(cph.params_.loc[var])
    se = float(cph.standard_errors_.loc[var])
    return {
        "beta": beta,
        "se": se,
        "hr": float(np.exp(beta)),
        "ci_lo": float(np.exp(beta - 1.96 * se)),
        "ci_hi": float(np.exp(beta + 1.96 * se)),
        "p": float(cph.summary.loc[var, "p"]),
    }


def cindex_from_risk(df: pd.DataFrame, time_col: str, event_col: str, risk: np.ndarray) -> float:
    return float(
        concordance_index(
            df[time_col].to_numpy(dtype=float),
            -np.asarray(risk, dtype=float).reshape(-1),
            df[event_col].to_numpy(dtype=int),
        )
    )


def model_cindex(cph: CoxPHFitter, fit_df: pd.DataFrame, time_col: str, event_col: str) -> float:
    risk = cph.predict_log_partial_hazard(fit_df).to_numpy().reshape(-1)
    return cindex_from_risk(fit_df, time_col, event_col, risk)


def lrt_stats(cph_full: CoxPHFitter, cph_reduced: CoxPHFitter, df_diff: int = 1) -> Tuple[float, float]:
    stat = 2.0 * (float(cph_full.log_likelihood_) - float(cph_reduced.log_likelihood_))
    if not np.isfinite(stat) or stat < 0:
        return np.nan, np.nan
    return stat, float(chi2.sf(stat, df_diff))


